void gfx_begin(gfx_band_t *b, unsigned band, uint16_t background)
{
    b->top = (int)(band * GFX_BAND);
    for (unsigned i = 0; i < GFX_W * GFX_BAND; ++i) b->px[i] = background;
}

void gfx_fill(gfx_band_t *b, int x, int y, int w, int h, uint16_t color)
{
    int x0 = x < 0 ? 0 : x, x1 = x + w > GFX_W ? GFX_W : x + w;
    int y0 = y < b->top ? b->top : y, y1 = y + h > b->top + GFX_BAND ? b->top + GFX_BAND : y + h;
    for (int row = y0; row < y1; ++row) {
        uint16_t *p = b->px + (row - b->top) * GFX_W;
        for (int col = x0; col < x1; ++col) p[col] = color;
    }
}

void gfx_frame(gfx_band_t *b, int x, int y, int w, int h, uint16_t color)
{
    gfx_fill(b, x, y, w, 1, color);
    gfx_fill(b, x, y + h - 1, w, 1, color);
    gfx_fill(b, x, y, 1, h, color);
    gfx_fill(b, x + w - 1, y, 1, h, color);
}

int gfx_text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n]) ++n;
    return n ? (n * 6 - 1) * scale : 0;
}

int gfx_text(gfx_band_t *b, int x, int y, const char *s, uint16_t color, int scale)
{
    if (!gfx_touches(b, y, 8 * scale)) return x + gfx_text_width(s, scale) + scale;
    for (; *s; ++s, x += 6 * scale) {
        int c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 0x20 || c > 0x5f) c = '?';
        const uint8_t *g = font[c - 0x20];
        for (int col = 0; col < 5; ++col)
            for (int row = 0; row < 8; ++row)
                if (g[col] & (1u << row)) gfx_fill(b, x + col * scale, y + row * scale, scale, scale, color);
    }
    return x;
}
