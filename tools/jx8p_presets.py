"""Generate engine/jx8p_presets.c: the JX-8P factory sounds for FM1-Electro (docs/adr/0039).

Source: fm1-synths (github.com/robtron-byte/fm1-synths, commit 2a7b4fa) jx8p/engine/jx_presets.c, there
generated from the user's JX-8P iOS app (FactoryPresets.swift): the 64 tones of the JX-8P (ROM V2.1,
parameter values only) and PG8X INIT. Here the values are renumbered without gaps (engine/jx8p.h: JX_*),
each sound gets an area from its category (BASS -> BASS, STR+BRASS and PAD -> STRINGS, the rest -> RHYTHM),
and PG8X INIT becomes INIT RHY, INIT STR and INIT BASS (mono) at the end.

Usage: jx8p_presets.py [path to fm1-synths/jx8p/engine/jx_presets.c]"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "fm1-synths" / "jx8p" / "engine" / "jx_presets.c"
# the JX-8P numbers kept, in order (jx.h: #11..#22, #26..#56, #58, then the patch level #59..#82)
KEEP = list(range(11, 23)) + list(range(26, 57)) + [58] + list(range(59, 83))
assert len(KEEP) == 68
RHYTHM, STRINGS, BASS = 1, 2, 3
AREA = {1: BASS, 8: STRINGS, 9: STRINGS}
KEY_MODE = KEEP.index(66)   # JP_KEY_MODE in jx.h: 59 + 7


def main():
    rows = re.findall(r'\{"([^"]+)", (\d+), \{([^}]*)\}\}', SRC.read_text())
    sounds, init = [], None
    for name, cat, vals in rows:
        v = [int(x) for x in vals.split(",")]
        assert len(v) == 83, name
        c = [v[i] for i in KEEP]
        if int(cat) == 0:
            init = c
            continue
        sounds.append((name, AREA.get(int(cat), RHYTHM), c))
    assert init and len(sounds) == 64
    for area, name in ((RHYTHM, "INIT RHY"), (STRINGS, "INIT STR"), (BASS, "INIT BASS")):
        c = list(init)
        if area == BASS:
            c[KEY_MODE] = 2
        sounds.append((name, area, c))
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only",
             " * Generated by tools/jx8p_presets.py from fm1-synths (github.com/robtron-byte/fm1-synths, commit 2a7b4fa)",
             " * jx8p/engine/jx_presets.c, there from the user's JX-8P iOS app (FactoryPresets.swift): the 64 factory",
             " * tones of the JX-8P (ROM V2.1, parameter values only) and its INIT for each area. Do not edit by hand. */",
             '#include "el_config.h"', "#if EL_SYNTH_JX", '#include "jx8p.h"', "",
             "const jx8p_preset_t jx8p_presets[] = {"]
    for name, area, c in sounds:
        assert len(name) <= 10, name
        lines.append(f'    {{"{name}", {area}, {{{", ".join(map(str, c))}}}}},')
    lines += ["};", "const unsigned jx8p_preset_count = sizeof jx8p_presets / sizeof jx8p_presets[0];", "#endif", ""]
    (ROOT / "engine" / "jx8p_presets.c").write_text("\n".join(lines))
    counts = {a: sum(1 for s in sounds if s[1] == a) for a in (RHYTHM, STRINGS, BASS)}
    print(len(sounds), "sounds: rhythm %d, strings %d, bass %d" % (counts[RHYTHM], counts[STRINGS], counts[BASS]))


if __name__ == "__main__":
    main()
