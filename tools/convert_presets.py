"""Generate engine/mks_presets.c from the MKS-50 iOS app's FactoryPresets.swift.
Usage: convert_presets.py <Mks50-iOS-/Shared/Model/FactoryPresets.swift> <output.c>"""
import re
import sys

# Patch-level parameters in engine/mks.h order after the 36 tone parameters,
# with the iOS app's defaults (Param.swift defaultValue).
EXTRAS = [
    ("keyMode", 0), ("portaTime", 30), ("portaSwitch", 0), ("volume", 100), ("keyShift", 12),
    ("pulseDetune", 64), ("pulseSync", 0), ("pulseEnvMod", 0), ("voiceDrift", 8), ("unisonDetune", 40),
    ("lfoWave", 0), ("lfoSync", 0), ("lfoDivision", 8), ("lfoKeySync", 0), ("envRetrigger", 0),
    ("delayMix", 0), ("reverbMix", 0), ("chordIndex", 0),
]

# Sound areas of FM1-Electro: 1 rhythmic sounds, 2 strings/pads, 3 bass.
AREA = {"zap": 1, "stab": 1, "sequence": 1, "fxPerc": 1, "keys": 1,
        "stringsBrass": 2, "pad": 2, "bass": 3}
BASS_NAMES = {"S&H BASS", "ARP BASS"}

MAKE = re.compile(r'make\(\.(\w+),\s*"([^"]+)",\s*\[([^\]]*)\](.*?)\)\s*,\s*(?=make\(|\]|//)', re.S)


def parse(text):
    body = text[text.index("private static let source"):text.index("private static func make")]
    for m in MAKE.finditer(body + "\nmake("):
        category, name, tone, rest = m.groups()
        values = [int(v) for v in re.findall(r"-?\d+", tone)]
        if len(values) != 36:
            raise SystemExit(f"{name}: {len(values)} tone values")
        extra = dict(EXTRAS)
        for key, arg in (("keyMode", "keyMode"), ("portaSwitch", "porta"), ("portaTime", "portaTime"),
                         ("chordIndex", "chord"), ("volume", "volume")):
            hit = re.search(rf"\b{arg}:\s*(\d+)", rest.split("extra:")[0])
            if hit:
                extra[key] = int(hit.group(1))
        if "extra:" in rest:
            for key, value in re.findall(r"\.(\w+):\s*(\d+)", rest.split("extra:")[1]):
                if key in extra:
                    extra[key] = int(value)
        area = 3 if name in BASS_NAMES else AREA.get(category, 0)
        yield area, name, category, values + [extra[k] for k, _ in EXTRAS]


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    presets = [p for p in parse(open(sys.argv[1], encoding="utf-8").read()) if p[0]]
    presets.sort(key=lambda p: p[0])
    out = ["/* SPDX-License-Identifier: GPL-3.0-only WITH GPL-3.0-linking-exception",
           " * Generated by tools/convert_presets.py from the MKS-50 iOS app's factory",
           " * sounds. Do not edit by hand. Control task only (Flash). */",
           '#include "mks.h"', "",
           "const mks_preset_t mks_presets[] = {"]
    for area, name, category, values in presets:
        out.append(f'    {{"{name}", {area}, {{{", ".join(str(v) for v in values)}}}}}, /* {category} */')
    out += ["};", "const unsigned mks_preset_count = sizeof mks_presets / sizeof mks_presets[0];", ""]
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
    counts = {a: sum(1 for p in presets if p[0] == a) for a in (1, 2, 3)}
    print(f"{len(presets)} presets: rhythm {counts[1]}, strings {counts[2]}, bass {counts[3]}")


if __name__ == "__main__":
    main()
